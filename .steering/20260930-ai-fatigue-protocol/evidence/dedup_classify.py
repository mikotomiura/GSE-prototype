def main(keep_path, out_path):
    keep = json.load(open(keep_path, encoding="utf-8"))
    want = {tuple(sorted(p)) for p in keep["keep"]}
    if set(C) != want:
        sys.exit(f"組が合わない: 足りない {sorted(want - set(C))} 余分 {sorted(set(C) - want)}")
    drop = [dict(a=a, b=b, cls="別の研究", match="姓が 2 名以上一致（観点 P3 だけ）", diff="名の頭文字が違う（同じ人と示す事実が無い）")
            for a, b in keep["drop"]]
    out = dict(executed=datetime.datetime.now(datetime.timezone(datetime.timedelta(hours=9))).isoformat(timespec="seconds"),
               note="メインの分け（design.md §7.3）。事実だけ。範囲の判断をしない。surname_only は判断 4 の名の頭文字の規則で別の研究。",
               pairs=[C[k] for k in sorted(C)], surname_only=drop)
    with open(out_path, "x", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
        f.write("\n")
    from collections import Counter
    print(Counter(v["cls"] for v in C.values()), "姓だけ", len(drop))


