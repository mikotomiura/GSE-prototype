"""Write the result tables of the manuscript from the aggregate JSON files of the study.

    python3 -I make_tables.py <results dir> <output dir>

<results dir> is experiments/20261012-public-keystroke-matching/results. The script reads main.json,
main_a4.json and main_a4_without_cpu_writer.json (the KeyTAR rows), enja15_main.json and
exploratory_{tail,margin,score_band}.json (aggregates only) and writes one .tex file per table
into <output dir> (sections/generated). The tables are included by the sections; values are never typed by hand.
Accuracies are printed in percent.
"""
import json
import os
import sys

MAIN_FORMS = ["R0", "R1", "R2", "R3", "R3-u", "R3-t(10)", "R3-t(100)", "R3-t(1000)",
              "R4(1)", "R4(2)", "R4(4)", "R4(8)", "R7(0.1)", "R7(0.25)", "R7(0.5)"]
ALL_FORMS = MAIN_FORMS + ["R5", "R6"]
MEASURES = [
    ("p_burst_mean_len", "P-burst length"),
    ("r_burst_mean_len", "R-burst length"),
    ("pause_mean_200ms", "Mean pause"),
    ("within_word_pause_mean", "Within-word pause"),
    ("between_word_pause_mean", "Between-word pause"),
    ("deletion_mean_len", "Deletion length"),
    ("deletion_proportion", "Deletion proportion"),
    ("insertion_mean_len", "Insertion length"),
    ("insertion_proportion", "Insertion proportion"),
    ("interval_variance_10", "Variance of production rate"),
]
ATTACKER_TEX = {"A0": "A0", "A1": "A1", "A1p": "A1$'$", "A2": "A2", "A2b": "A2-b", "A3": "A3",
                "A3-mean": "A3 (mean)", "A3-sum": "A3 (sum)", "A3-len": "A3 (length)",
                "A2-lam4": "A2 ($\\lambda{=}4$)", "A2-lam16": "A2 ($\\lambda{=}16$)"}


def form_tex(f):
    return f.replace("(1000)", "(1{,}000)")


def pct(x):
    """A proportion in percent: two decimals below 1%, one decimal otherwise."""
    v = 100.0 * x
    if abs(v) < 1.0 and v != 0.0:
        return f"{v:.2f}"
    return f"{v:.1f}"


def ci(c):
    return f"[{pct(c[0])}, {pct(c[1])}]"


def times(x):
    if x >= 100:
        return f"{x:,.0f}".replace(",", "{,}")
    if x >= 10:
        return f"{x:.0f}"
    return f"{x:.1f}"


def attacker(v):
    name = ATTACKER_TEX[v["attacker"]]
    share = v["share_selected"].get(v["attacker"], 1.0)
    if share < 0.995:
        name += f" ({100 * share:.0f})"
    return name


def write(out, name, lines):
    with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
        fh.write("% Generated by make_tables.py from the aggregate results; do not edit by hand.\n")
        fh.write("\n".join(lines) + "\n")


def main_table(m, n, with_utility):
    s, c, uf = m["strongest"], m["cells"], m["utility_figure"]
    rows = []
    forms = MAIN_FORMS
    if not with_utility:
        # Without the utility columns, the rows of R3-t(w) are merged when every value is the same for all w.
        keys = ("acc", "ci", "attacker", "uplift_over_A0", "uplift_ci")
        same = all(s[f"full|R3-t({w})|{n}"][k] == s[f"full|R3-t(10)|{n}"][k] for w in (100, 1000) for k in keys)
        if same:
            forms = [f for f in MAIN_FORMS if f not in ("R3-t(100)", "R3-t(1000)")]
    for f in forms:
        v = s[f"full|{f}|{n}"]
        a0 = c[f"full|{f}|A0|{n}"]["acc"]
        name = "R3-t($w$), all $w$" if (not with_utility and f == "R3-t(10)" and len(forms) < len(MAIN_FORMS)) else form_tex(f)
        row = [name, pct(a0), f"{pct(v['acc'])} {ci(v['ci'])}", attacker(v), times(v["x_chance"]),
               f"{pct(v['uplift_over_A0'])} {ci(v['uplift_ci'])}"]
        if with_utility:
            u = uf[f]
            row += [f"{u['ok']}/{u['approx']}/{u['none']}", f"{u['median_spearman_r0']:.2f}"]
        rows.append(" & ".join(row) + " \\\\")
    return rows


def figure_coords(m):
    s, uf = m["strongest"], m["utility_figure"]
    lines = []
    for f in MAIN_FORMS:
        lines.append(f"% {f}: {s[f'full|{f}|1000']['x_chance']:.4g} {uf[f]['median_spearman_r0']:.4f}")
    return lines


def cells_table(m):
    c = m["cells"]
    rows = []
    for f in ALL_FORMS:
        names = sorted({k.split("|")[2] for k in c if k.startswith(f"full|{f}|")},
                       key=lambda a: list(ATTACKER_TEX).index(a))
        for a in names:
            if a == "A3" and f == "R3-u":
                continue  # the better version, already listed as A3 (mean)
            vals = [c.get(f"full|{f}|{a}|{n}") for n in ("10", "100", "1000")]
            cells = [f"{pct(v['acc'])} {ci(v['ci'])}" if v else "--" for v in vals]
            rows.append(" & ".join([form_tex(f), ATTACKER_TEX[a]] + cells) + " \\\\")
    return rows


def secondary_table(m):
    """Rank of the true text and accuracy per writer for the attacker selected at N = 1,000."""
    s, c = m["strongest"], m["cells"]
    rows = []
    for f in ALL_FORMS:
        a = s[f"full|{f}|1000"]["attacker"]
        if f == "R3-u" and a == "A3":
            a = "A3-mean" if s[f"full|{f}|1000"]["acc"] == c[f"full|{f}|A3-mean|1000"]["acc"] else "A3-sum"
        v = c[f"full|{f}|{a}|1000"]
        p = v.get("writer_p10_p50_p90") or [None] * 3
        rows.append(" & ".join([form_tex(f), ATTACKER_TEX[a], pct(v["acc"]), pct(v["top5"]), f"{v['mrr']:.3f}",
                                "/".join(pct(x) for x in p), str(v["only_true_inf"]), str(v["all_inf"])]) + " \\\\")
    return rows


def window_table(m):
    s = m["strongest"]
    rows = []
    for f in ALL_FORMS:
        cells = []
        for n in ("1000", "10"):
            for k in ("5", "10", "20", "50"):
                v = s.get(f"window|{f}|{n}|{k}")
                cells.append(f"{pct(v['acc'])} ({ATTACKER_TEX[v['attacker']]})" if v else "--")
        rows.append(" & ".join([form_tex(f)] + cells) + " \\\\")
    return rows


# A4 uses one reconstruction for R0 to R3 (the same intervals), so these forms are one row; R3-t(w) has its own.
A4_GROUPS = [("R0 to R3", ["R0", "R1", "R2", "R3"]), ("R3-t(10)", ["R3-t(10)"]), ("R3-t(100)", ["R3-t(100)"]),
             ("R3-t(1000)", ["R3-t(1000)"])]


def a4_cell(ref, kind, forms, rest):
    """The A4 cell of a group of forms; stops if the forms of the group do not give the same values."""
    vals = [ref[f"{kind}|{f}|A4|{rest}"] for f in forms]
    if any(v != vals[0] for v in vals[1:]):
        raise SystemExit(f"A4 differs within {forms} at {kind}|{rest}")
    return vals[0]


def a4_main_row(ref, n):
    g = a4_cell(ref, "full", A4_GROUPS[0][1], n)
    t = [a4_cell(ref, "full", fs, n) for _, fs in A4_GROUPS[1:]]
    acc = [pct(v["acc"]) for v in t]
    text = f"R0 to R3: {pct(g['acc'])} {ci(g['ci'])}; R3-t(10), (100), (1{{,}}000): {acc[0]}, {acc[1]} and {acc[2]}"
    return [f"A4 on R0 to R3-t & \\multicolumn{{7}}{{l}}{{{text}}} \\\\"]


def a4_tables(ref, ref_wo):
    """KeyTAR on full texts at every N and on windows, with all 500 writers and without the CPU writer."""
    if set(ref) != set(ref_wo):
        raise SystemExit("the cells of main_a4_without_cpu_writer.json differ from reference_A4 of main_a4.json")
    full, win = [], []
    for name, fs in A4_GROUPS:
        for r in (ref, ref_wo):
            writers = str(a4_cell(r, "full", fs, "1000")["writers"])
            cells = [a4_cell(r, "full", fs, n) for n in ("10", "100", "1000")]
            full.append(" & ".join([form_tex(name), writers] + [f"{pct(v['acc'])} {ci(v['ci'])}" for v in cells])
                        + " \\\\")
            wc = [a4_cell(r, "window", fs, f"{n}|{k}") for n in ("1000", "10") for k in ("5", "10", "20", "50")]
            win.append(" & ".join([form_tex(name), writers] + [pct(v["acc"]) for v in wc]) + " \\\\")
    return full, win


def utility_table(m, key):
    u = m["utility"]
    forms = ["R0", "R2", "R3", "R3-u", "R3-t(10)", "R3-t(100)", "R3-t(1000)", "R7(0.1)", "R7(0.25)", "R7(0.5)"]
    rows = []
    for mk, label in MEASURES:
        cells = []
        for f in forms:
            v = u.get(f"{mk}|{f}")
            q = v.get(key) if v else None
            cells.append(f"{q['mean']:.2f}" if q and q.get("mean") is not None else "--")
        rows.append(" & ".join([label] + cells) + " \\\\")
    return rows


def other_tables(m):
    rs = m["rebuilt_split"]
    rows = []
    for f in ["R0", "R1", "R2", "R3", "R3-u", "R7(0.1)"]:
        for a in ("A1", "A1p", "A2", "A3"):
            v = rs["cells"].get(f"full|{f}|{a}|1000")
            if v:
                rows.append(" & ".join([form_tex(f), ATTACKER_TEX[a], f"{pct(v['match']['acc'])} {ci(v['match']['ci'])}",
                                        f"{pct(v['mismatch']['acc'])} {ci(v['mismatch']['ci'])}"]) + " \\\\")
    nc = m["negative_control"]["fixed_attacker"]
    neg = []
    for f in MAIN_FORMS:
        a, b = nc[f"full|{f}|10"], nc[f"full|{f}|1000"]
        neg.append(" & ".join([form_tex(f), ATTACKER_TEX[a["attacker"]], f"{pct(a['acc'])} {ci(a['ci'])}",
                               ATTACKER_TEX[b["attacker"]], f"{pct(b['acc'])} {ci(b['ci'])}"]) + " \\\\")
    ow = []
    for f in MAIN_FORMS:
        v = m["open_world"][f"full|{f}|1000"]
        ow.append(" & ".join([form_tex(f), ATTACKER_TEX[v["costs_of"]] if v["costs_of"] in ATTACKER_TEX else v["costs_of"],
                              f"{v['auc']:.3f} [{v['ci'][0]:.3f}, {v['ci'][1]:.3f}]"]) + " \\\\")
    return rows, neg, ow


def enja_table(d):
    forms = ["R3j", "R3j-t(10)", "R3j-t(100)", "R3j-t(1000)", "R4(1)", "R4(2)", "R4(4)", "R4(8)"]
    rows = []
    for f in forms:
        for n in ("all", "10"):
            a0, a2 = d["cells"][f"{f}|A0|{n}"], d["cells"][f"{f}|A2|{n}"]
            rows.append(" & ".join([form_tex(f), "all" if n == "all" else "10", pct(a2["chance"]),
                                    f"{pct(a0['acc'])} {ci(a0['ci'])}", f"{pct(a2['acc'])} {ci(a2['ci'])}",
                                    f"{pct(a2['diff_chance'])} {ci(a2['diff_chance_ci'])}",
                                    f"{pct(a2['diff_A0'])} {ci(a2['diff_A0_ci'])}",
                                    "yes" if a2.get("exceeds") else "no"]) + " \\\\")
    return rows


def explore_tables(tail, margin, band):
    t_rows, m_rows, b_rows = [], [], []
    for f in MAIN_FORMS:
        for n in ("1000", "10"):
            v = tail[f"full|{f}|{n}"]
            t_rows.append(" & ".join([form_tex(f), "1{,}000" if n == "1000" else "10", ATTACKER_TEX[v["attacker"]],
                                      f"{pct(v['p95']['value'])} {ci(v['p95']['ci'])}",
                                      f"{pct(v['p99']['value'])} {ci(v['p99']['ci'])}",
                                      f"{pct(v['share_acc_1']['value'])} {ci(v['share_acc_1']['ci'])}"]) + " \\\\")
            mv = margin[f"full|{f}|{n}"]
            cv = {p["q"]: p for p in mv["curve"]}
            cells = [f"{pct(cv[q]['coverage'])}/{pct(cv[q]['precision'])}" for q in (0, 20, 50, 80, 90)]
            m_rows.append(" & ".join([form_tex(f), "1{,}000" if n == "1000" else "10", ATTACKER_TEX[mv["attacker"]]] + cells)
                          + " \\\\")
            bv = band[f"full|{f}|{n}"]
            b_rows.append(" & ".join([form_tex(f), "1{,}000" if n == "1000" else "10", ATTACKER_TEX[bv["attacker"]],
                                      pct(bv["band0"]["acc"]), pct(bv["band1"]["acc"]), pct(bv["band2"]["acc"]),
                                      f"{pct(bv['top_minus_bottom']['value'])} {ci(bv['top_minus_bottom']['ci'])}"]) + " \\\\")
    return t_rows, m_rows, b_rows


def main():
    res, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    m = json.load(open(os.path.join(res, "main.json"), encoding="utf-8"))["main500"]
    write(out, "main-1000.tex", main_table(m, "1000", True))
    write(out, "main-10.tex", main_table(m, "10", False))
    write(out, "figure-coords.tex", figure_coords(m))
    write(out, "cells.tex", cells_table(m))
    write(out, "secondary.tex", secondary_table(m))
    write(out, "windows.tex", window_table(m))
    write(out, "utility-r0.tex", utility_table(m, "spearman_r0"))
    write(out, "utility-score.tex", utility_table(m, "spearman_score"))
    ref = json.load(open(os.path.join(res, "main_a4.json"), encoding="utf-8"))["main500"]["reference_A4"]
    ref_wo = json.load(open(os.path.join(res, "main_a4_without_cpu_writer.json"), encoding="utf-8"))["reference_A4"]
    write(out, "main-a4-1000.tex", a4_main_row(ref, "1000"))
    write(out, "main-a4-10.tex", a4_main_row(ref, "10"))
    a4_full, a4_win = a4_tables(ref, ref_wo)
    write(out, "a4-full.tex", a4_full)
    write(out, "a4-windows.tex", a4_win)
    split, neg, ow = other_tables(m)
    write(out, "split.tex", split)
    write(out, "negative.tex", neg)
    write(out, "open-world.tex", ow)
    d = json.load(open(os.path.join(res, "enja15_main.json"), encoding="utf-8"))
    write(out, "enja.tex", enja_table(d))
    tail = json.load(open(os.path.join(res, "exploratory_tail.json"), encoding="utf-8"))["analysis"]
    margin = json.load(open(os.path.join(res, "exploratory_margin.json"), encoding="utf-8"))["analysis"]
    band = json.load(open(os.path.join(res, "exploratory_score_band.json"), encoding="utf-8"))["analysis"]
    t, mg, b = explore_tables(tail, margin, band)
    write(out, "explore-tail.tex", t)
    write(out, "explore-margin.tex", mg)
    write(out, "explore-band.tex", b)


if __name__ == "__main__":
    main()
