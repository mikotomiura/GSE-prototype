MAIN_FORMS = ["R0", "R1", "R2", "R3", "R3-u", "R3-t(10)", "R3-t(100)", "R3-t(1000)",
              "R4(1)", "R4(2)", "R4(4)", "R4(8)", "R7(0.1)", "R7(0.25)", "R7(0.5)"]
ALL_FORMS = MAIN_FORMS + ["R5", "R6"]
ALL_WRITERS = 4992  # all writers after exclusion, as stated in Appendix E
MEASURES = [
    ("p_burst_mean_len", "P-burst length"),
    ("r_burst_mean_len", "R-burst length"),
    ("pause_mean_200ms", "Mean pause"),
    ("within_word_pause_mean", "Within-word pause"),
    ("between_word_pause_mean", "Between-word pause"),
    ("deletion_mean_len", "Deletion length"),
    ("deletion_proportion", "Deletion proportion"),
    ("insertion_mean_len", "Insertion length"),
    ("insertion_proportion", "Insertion proportion"),
    ("interval_variance_10", "Variance of production rate"),
]
ATTACKER_TEX = {"A0": "A0", "A1": "A1", "A1p": "A1$'$", "A2": "A2", "A2b": "A2-b", "A3": "A3",
                "A3-mean": "A3 (mean)", "A3-sum": "A3 (sum)", "A3-len": "A3 (length)",
                "A2-lam4": "A2 ($\\lambda{=}4$)", "A2-lam16": "A2 ($\\lambda{=}16$)"}
LAMS = (2, 4, 8, 16)  # the grid of exploratory analyses 6 and 7
for _lam in LAMS:
    ATTACKER_TEX[f"A2.lam{_lam}"] = f"A2 ($\\lambda{{=}}{_lam}$)"
    ATTACKER_TEX[f"A1p.lam{_lam}"] = f"A1$'$ ($\\lambda{{=}}{_lam}$)"
    ATTACKER_TEX[f"A2scan.lam{_lam}"] = f"A2-scan ($\\lambda{{=}}{_lam}$)"


def form_tex(f):
    return f.replace("(1000)", "(1{,}000)")


def pct(x):
    """A proportion in percent: two decimals below 1%, one decimal otherwise."""
    v = 100.0 * x
    if abs(v) < 1.0 and v != 0.0:
        return f"{v:.2f}"
    return f"{v:.1f}"


def ci(c):
    return f"[{pct(c[0])}, {pct(c[1])}]"


def times(x):
    if x >= 100:
        return f"{x:,.0f}".replace(",", "{,}")
    if x >= 10:
        return f"{x:.0f}"
    return f"{x:.1f}"


def a3_key(m, f, a, n):
    """On R3-u the attacker A3 is the better of its two timing terms; it is named by the one it equals (stops if
    neither), so that every table names it the same way."""
    if f != "R3-u" or a != "A3":
        return a
    c = m["cells"]
    acc = c[f"full|R3-u|A3|{n}"]["acc"]
    for k in ("A3-mean", "A3-sum"):
        if c[f"full|R3-u|{k}|{n}"]["acc"] == acc:
            return k
    raise SystemExit(f"A3 on R3-u at N = {n} equals neither A3-mean nor A3-sum")


def attacker(v, m=None, f=None, n=None):
    name = ATTACKER_TEX[a3_key(m, f, v["attacker"], n) if m else v["attacker"]]
    share = v["share_selected"][v["attacker"]]
    if share < 0.995:
        name += f" ({100 * share:.0f})"
    return name


def write(out, name, lines):
    with open(os.path.join(out, name), "w", encoding="utf-8") as fh:
        fh.write("% Generated by make_tables.py from the aggregate results; do not edit by hand.\n")
        fh.write("\n".join(lines) + "\n")


def main_table(m, n, with_utility):
    s, c, uf = m["strongest"], m["cells"], m["utility_figure"]
    rows = []
    forms = MAIN_FORMS
    if not with_utility:
        # Without the utility columns, the rows of R3-t(w) are merged when every value is the same for all w.
        keys = ("acc", "ci", "attacker", "uplift_over_A0", "uplift_ci")
        same = all(s[f"full|R3-t({w})|{n}"][k] == s[f"full|R3-t(10)|{n}"][k] for w in (100, 1000) for k in keys) and \
            all(c[f"full|R3-t({w})|A0|{n}"]["acc"] == c[f"full|R3-t(10)|A0|{n}"]["acc"] for w in (100, 1000))
        if same:
            forms = [f for f in MAIN_FORMS if f not in ("R3-t(100)", "R3-t(1000)")]
    for f in forms:
        v = s[f"full|{f}|{n}"]
        a0 = c[f"full|{f}|A0|{n}"]["acc"]
        name = "R3-t($w$), all $w$" if (not with_utility and f == "R3-t(10)" and len(forms) < len(MAIN_FORMS)) else form_tex(f)
        row = [name, pct(a0), f"{pct(v['acc'])} {ci(v['ci'])}", attacker(v, m, f, n), times(v["x_chance"]),
               f"{pct(v['uplift_over_A0'])} {ci(v['uplift_ci'])}"]
        if with_utility:
            u = uf[f]
            row += [f"{u['ok']}/{u['approx']}/{u['none']}", f"{u['median_spearman_r0']:.2f}"]
        rows.append(" & ".join(row) + " \\\\")
    return rows


def figure_coords(m):
    s, uf = m["strongest"], m["utility_figure"]
    lines = []
    for f in MAIN_FORMS:
        lines.append(f"% {f}: {s[f'full|{f}|1000']['x_chance']:.4g} {uf[f]['median_spearman_r0']:.4f}")
    return lines


def cells_table(m):
    c = m["cells"]
    rows = []
    for f in ALL_FORMS:
        names = sorted({k.split("|")[2] for k in c if k.startswith(f"full|{f}|")},
                       key=lambda a: list(ATTACKER_TEX).index(a))
        for a in names:
            if a == "A3" and f == "R3-u":
                continue  # the better version, already listed as A3 (mean)
            vals = [c.get(f"full|{f}|{a}|{n}") for n in ("10", "100", "1000")]
            cells = [f"{pct(v['acc'])} {ci(v['ci'])}" if v else "--" for v in vals]
            rows.append(" & ".join([form_tex(f), ATTACKER_TEX[a]] + cells) + " \\\\")
    return rows


def secondary_table(m):
    """Rank of the true text and accuracy per writer for the attacker selected at N = 1,000."""
    s, c = m["strongest"], m["cells"]
    rows = []
    for f in ALL_FORMS:
        a = a3_key(m, f, s[f"full|{f}|1000"]["attacker"], "1000")
        v = c[f"full|{f}|{a}|1000"]
        p = v["writer_p10_p50_p90"]
        rows.append(" & ".join([form_tex(f), ATTACKER_TEX[a], pct(v["acc"]), pct(v["top5"]), f"{v['mrr']:.3f}",
                                "/".join(pct(x) for x in p), str(v["only_true_inf"]), str(v["all_inf"])]) + " \\\\")
    return rows


def window_table(m):
    s = m["strongest"]
    rows = []
    for f in ALL_FORMS:
        cells = []
        for n in ("1000", "10"):
            for k in ("5", "10", "20", "50"):
                v = s[f"window|{f}|{n}|{k}"]
                if f == "R3-u" and v["attacker"] == "A3":
                    raise SystemExit(f"window|R3-u|{n}|{k}: A3 on windows is not named by its timing term")
                cells.append(f"{pct(v['acc'])} ({ATTACKER_TEX[v['attacker']]})")
        rows.append(" & ".join([form_tex(f)] + cells) + " \\\\")
    return rows


# A4 uses one reconstruction for R0 to R3 (the same intervals), so these forms are one row; R3-t(w) has its own.
A4_GROUPS = [("R0 to R3", ["R0", "R1", "R2", "R3"]), ("R3-t(10)", ["R3-t(10)"]), ("R3-t(100)", ["R3-t(100)"]),
             ("R3-t(1000)", ["R3-t(1000)"])]


def a4_cell(ref, kind, forms, rest):
    """The A4 cell of a group of forms; stops if the forms of the group do not give the same values."""
    vals = [ref[f"{kind}|{f}|A4|{rest}"] for f in forms]
    if any(v != vals[0] for v in vals[1:]):
        raise SystemExit(f"A4 differs within {forms} at {kind}|{rest}")
    return vals[0]


def a4_main_row(ref, n):
    g = a4_cell(ref, "full", A4_GROUPS[0][1], n)
    t = [a4_cell(ref, "full", fs, n) for _, fs in A4_GROUPS[1:]]
    acc = [pct(v["acc"]) for v in t]
    text = f"R0 to R3: {pct(g['acc'])} {ci(g['ci'])}; R3-t(10), (100), (1{{,}}000): {acc[0]}, {acc[1]} and {acc[2]}"
    return [f"A4 on R0 to R3-t & \\multicolumn{{7}}{{l}}{{{text}}} \\\\"]


A4_WITHOUT_MAX_POINTS = 0.12  # the text states that no accuracy changed by more than this without the CPU writer


def a4_tables(ref, ref_wo):
    """KeyTAR on full texts at every N and on windows, with all 500 writers. The values without the CPU writer are
    not tabulated (their difference would give one writer's values); only their largest change is checked."""
    if set(ref) != set(ref_wo):
        raise SystemExit("the cells of main_a4_without_cpu_writer.json differ from reference_A4 of main_a4.json")
    diffs = []
    for k in ref:
        a, b = ref[k].get("acc") if isinstance(ref[k], dict) else None, ref_wo[k].get("acc") if isinstance(ref_wo[k], dict) else None
        if a is None or b is None or not (math.isfinite(a) and math.isfinite(b)):
            raise SystemExit(f"KeyTAR cell {k} has no finite accuracy with or without the CPU writer")
        diffs.append(abs(a - b) * 100)
    for name, fs in A4_GROUPS:  # the group check and a control that the second file lacks exactly one writer
        w, w_wo = a4_cell(ref, "full", fs, "1000")["writers"], a4_cell(ref_wo, "full", fs, "1000")["writers"]
        if w_wo != w - 1:
            raise SystemExit(f"KeyTAR without the CPU writer has {w_wo} writers on {name}, not {w - 1}")
    if not diffs or max(diffs) > A4_WITHOUT_MAX_POINTS:
        raise SystemExit(f"KeyTAR without the CPU writer changed an accuracy by more than {A4_WITHOUT_MAX_POINTS} points")
    full, win = [], []
    for name, fs in A4_GROUPS:
        for r in (ref,):
            writers = str(a4_cell(r, "full", fs, "1000")["writers"])
            cells = [a4_cell(r, "full", fs, n) for n in ("10", "100", "1000")]
            full.append(" & ".join([form_tex(name), writers] + [f"{pct(v['acc'])} {ci(v['ci'])}" for v in cells])
                        + " \\\\")
            wc = [a4_cell(r, "window", fs, f"{n}|{k}") for n in ("1000", "10") for k in ("5", "10", "20", "50")]
            win.append(" & ".join([form_tex(name), writers] + [pct(v["acc"]) for v in wc]) + " \\\\")
    return full, win


SCORE_SHIFT_TEXT = {"R2": 2, "R3": 2, "R7(0.25)": 3, "R7(0.5)": 4}  # stated in Section 7.3


def check_score_shift(m):
    """The text counts, for some forms, the measures whose correlation with the human score moved by 0.1 or more
    from R0 (means over the prompts); stop if the aggregates give other counts."""
    u = m["utility"]
    for f, stated in SCORE_SHIFT_TEXT.items():
        n = 0
        for mk, _ in MEASURES:
            a, b = u[f"{mk}|R0"]["spearman_score"], u[f"{mk}|{f}"]["spearman_score"]
            if not (a and b and a.get("mean") is not None and b.get("mean") is not None
                    and math.isfinite(a["mean"]) and math.isfinite(b["mean"])):
                raise SystemExit(f"score correlation of {mk} missing on R0 or {f}")
            d = abs(b["mean"] - a["mean"])
            if abs(d - 0.1) < 1e-6:
                raise SystemExit(f"score shift of {mk} on {f} is at the 0.1 boundary; the count is not robust")
            n += d > 0.1
        if n != stated:
            raise SystemExit(f"score shift on {f}: {n} measures, the text states {stated}")


def utility_table(m, key):
    u = m["utility"]
    forms = ["R0", "R2", "R3", "R3-u", "R3-t(10)", "R3-t(100)", "R3-t(1000)", "R7(0.1)", "R7(0.25)", "R7(0.5)"]
    rows = []
    for mk, label in MEASURES:
        cells = []
        for f in forms:
            q = u[f"{mk}|{f}"][key]  # a missing key stops; a measure that was not computed has no mean
            cells.append(f"{q['mean']:.2f}" if q and q.get("mean") is not None else "--")
        rows.append(" & ".join([label] + cells) + " \\\\")
    return rows


