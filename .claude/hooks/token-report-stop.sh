#!/usr/bin/env bash
# token-report-stop.sh
# Stop hook — .codex/budget.json の当日 codex token 使用量を
# .steering/_token_log.md に追記し、セッション終了時にサマリを表示する。

set -uo pipefail

if [ ! -f .codex/budget.json ]; then
    exit 0
fi

TODAY=$(date +%Y-%m-%d)
DATA=$(cat .codex/budget.json)
DATE_REC=$(echo "$DATA" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('today',{}).get('date',''))" 2>/dev/null || echo "")
USED=$(echo "$DATA" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('today',{}).get('tokens_used',0))" 2>/dev/null || echo "0")
INVS=$(echo "$DATA" | python3 -c "import sys,json; d=json.load(sys.stdin); print(d.get('today',{}).get('invocations',0))" 2>/dev/null || echo "0")

# 当日データでなければ何もしない
if [ "$DATE_REC" != "$TODAY" ]; then
    exit 0
fi

# 使用量 0 なら無報告
if [ "$USED" -eq 0 ]; then
    exit 0
fi

# 冪等キー: 同一セッションで Stop が複数回走っても重複記録しない
KEY="$TODAY:tokens=$USED:invs=$INVS"
LAST_KEY_FILE=.steering/_token_log.last_key
if [ -f "$LAST_KEY_FILE" ] && [ "$(cat "$LAST_KEY_FILE")" = "$KEY" ]; then
    exit 0
fi

mkdir -p .steering
LOG=.steering/_token_log.md
LINE="- $TODAY (session end): codex tokens=$USED, invocations=$INVS"

# atomic append with flock (Windows git-bash: flock は利用可)
(
    flock -x 9 2>/dev/null || true
    if [ ! -f "$LOG" ]; then
        {
            echo "# Codex Token Usage Log"
            echo
            echo "Generated by .claude/hooks/token-report-stop.sh on session end."
            echo
        } > "$LOG"
    fi
    if grep -q "^- $TODAY" "$LOG" 2>/dev/null; then
        sed -i "s|^- $TODAY.*|$LINE|" "$LOG"
    else
        echo "$LINE" >> "$LOG"
    fi
    echo "$KEY" > "$LAST_KEY_FILE"
) 9>> "${LOG}.lock"

echo "[stop] codex usage today: $USED tokens / $INVS invocations (logged to $LOG)"
exit 0
