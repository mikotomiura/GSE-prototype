#!/usr/bin/env bash
# token-report-stop.sh
# Stop hook — .codex/budget.json の当日 codex token 使用量を
# .steering/_token_log.md に追記し、セッション終了時にサマリを表示する。

set -uo pipefail

# repo root 基準で参照する (cwd 依存だと当日の使用量を取り落とす)
ROOT=$(git rev-parse --show-toplevel 2>/dev/null || echo .)
BUDGET_FILE="$ROOT/.codex/budget.json"
if [ ! -f "$BUDGET_FILE" ]; then
    exit 0
fi

# JSON パースは python (jq 非依存)。本 hook は**報告専用**でゲートではないため、
# python 不在 / 破損時は静かに終わる (guard 系の fail-closed とは扱いが違う)。
PYTHON=$(command -v python3 || command -v python || true)
if [ -z "$PYTHON" ]; then
    echo "[stop] WARN: python not found; skipping codex token report" >&2
    exit 0
fi

# Windows git-bash の日本語ロケール (cp932) 対策
export PYTHONUTF8=1 PYTHONIOENCODING=utf-8

TODAY=$(date +%Y-%m-%d)
# 空白区切り + cut は date に空白が入ると崩れる。1 行 1 値にして read で受ける。
# 数値は int() で正規化し、非数値ならここで諦める (報告専用なので fail-open で良い)。
if ! TODAY_INFO=$("$PYTHON" - "$BUDGET_FILE" 2>/dev/null <<'PY'
import json, sys
d = json.load(open(sys.argv[1], encoding='utf-8')).get('today', {})
print(str(d.get('date', '')).replace('\n', ' '))
print(int(d.get('tokens_used', 0)))
print(int(d.get('invocations', 0)))
PY
); then
    echo "[stop] WARN: .codex/budget.json を読めない / 値が不正; skipping codex token report" >&2
    exit 0
fi
{ IFS= read -r DATE_REC; IFS= read -r USED; IFS= read -r INVS; } <<EOF_INFO
$TODAY_INFO
EOF_INFO

# 当日データでなければ何もしない
if [ "$DATE_REC" != "$TODAY" ]; then
    exit 0
fi

# 使用量 0 なら無報告
if [ "$USED" -eq 0 ]; then
    exit 0
fi

# 冪等キー: 同一セッションで Stop が複数回走っても重複記録しない
KEY="$TODAY:tokens=$USED:invs=$INVS"
LAST_KEY_FILE="$ROOT/.steering/_token_log.last_key"
if [ -f "$LAST_KEY_FILE" ] && [ "$(cat "$LAST_KEY_FILE")" = "$KEY" ]; then
    exit 0
fi

mkdir -p "$ROOT/.steering"
LOG="$ROOT/.steering/_token_log.md"
LINE="- $TODAY (session end): codex tokens=$USED, invocations=$INVS"

# flock は使わない: macOS に無く、`set -e` の無いスクリプトでは
# `flock: command not found` でも処理が続くだけで排他にならない (= 壊れたロック)。
# 上の冪等キーで多重記録は防いでいるため、ロック無しで実害は無い。
if [ ! -f "$LOG" ]; then
    {
        echo "# Codex Token Usage Log"
        echo
        echo "Generated by .claude/hooks/token-report-stop.sh on session end."
        echo
    } > "$LOG"
fi
if grep -q "^- $TODAY" "$LOG" 2>/dev/null; then
    # `sed -i "式" file` は BSD sed (macOS) で式がバックアップ拡張子として食われ失敗する。
    # `-i.bak` + 削除なら GNU/BSD 両対応 (git-bash / macOS 共通)。
    # $LINE は python で int 化した値のみで構成されるため sed の特殊文字を含まない
    sed -i.bak "s|^- $TODAY.*|$LINE|" "$LOG"
    rm -f "$LOG.bak"
else
    echo "$LINE" >> "$LOG"
fi
echo "$KEY" > "$LAST_KEY_FILE"

echo "[stop] codex usage today: $USED tokens / $INVS invocations (logged to $LOG)"
exit 0
